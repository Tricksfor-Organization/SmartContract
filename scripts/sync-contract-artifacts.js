#!/usr/bin/env node

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const solc = require("solc");

const root = path.resolve(__dirname, "..");
const checkOnly = process.argv.includes("--check");
const contracts = ["TricksforBoosterNFT", "TricksforBoosterStaking"];
const compilationTargets = [
  ...contracts.map((name) => ({ name, sourceName: `contracts/${name}.sol`, publish: true })),
  { name: "ReentrantERC721", sourceName: "contracts/test/ReentrantERC721.sol", publish: false }
];

const sources = {};

function loadSource(sourceName) {
  if (sources[sourceName] !== undefined) return;
  const filePath = sourceName.startsWith("@")
    ? path.join(root, "node_modules", sourceName)
    : path.join(root, sourceName);
  const content = fs.readFileSync(filePath, "utf8");
  sources[sourceName] = { content };

  const importPattern = /import\s+(?:[^"']*?\s+from\s+)?["']([^"']+)["']\s*;/g;
  for (const match of content.matchAll(importPattern)) {
    const imported = match[1].startsWith(".")
      ? path.posix.normalize(path.posix.join(path.posix.dirname(sourceName), match[1]))
      : match[1];
    loadSource(imported);
  }
}

for (const target of compilationTargets) loadSource(target.sourceName);

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: {
      "*": {
        "*": ["abi", "metadata", "devdoc", "userdoc", "storageLayout", "evm.bytecode", "evm.deployedBytecode", "evm.methodIdentifiers"],
        "": ["ast"]
      }
    }
  }
};

function resolveImport(importPath) {
  const candidates = [path.join(root, importPath), path.join(root, "node_modules", importPath)];
  const resolved = candidates.find(fs.existsSync);
  return resolved
    ? { contents: fs.readFileSync(resolved, "utf8") }
    : { error: `Unable to resolve Solidity import: ${importPath}` };
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: resolveImport }));
const buildInfoId = `solc-0_8_26-${crypto.createHash("sha256").update(JSON.stringify(input)).digest("hex")}`;
const diagnostics = output.errors ?? [];
for (const diagnostic of diagnostics) {
  const stream = diagnostic.severity === "error" ? process.stderr : process.stdout;
  stream.write(`${diagnostic.formattedMessage}\n`);
}
if (diagnostics.some((diagnostic) => diagnostic.severity === "error")) {
  process.exit(1);
}

function artifactFor(name, sourceName = `contracts/${name}.sol`) {
  const compiled = output.contracts[sourceName][name];
  return {
    _format: "hh3-artifact-1",
    contractName: name,
    sourceName,
    abi: compiled.abi,
    bytecode: `0x${compiled.evm.bytecode.object}`,
    deployedBytecode: `0x${compiled.evm.deployedBytecode.object}`,
    linkReferences: compiled.evm.bytecode.linkReferences,
    deployedLinkReferences: compiled.evm.deployedBytecode.linkReferences,
    immutableReferences: compiled.evm.deployedBytecode.immutableReferences ?? {},
    inputSourceName: sourceName,
    buildInfoId
  };
}

function renderCSharp(name, artifact) {
  const abi = JSON.stringify(artifact.abi).replaceAll('"', '""');
  return `namespace Tricksfor.Blockchain.Booster.Abis
{
    /// <summary>
    /// ABI and bytecode for ${name}. Generated by scripts/sync-contract-artifacts.js.
    /// </summary>
    internal static class ${name}Abi
    {
        public const string Abi = @"${abi}";

        public const string Bytecode = "${artifact.bytecode}";
    }
}
`;
}

function assertOrWrite(filePath, expected) {
  if (checkOnly) {
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
    if (actual !== expected) {
      console.error(`Out of sync: ${path.relative(root, filePath)}`);
      process.exitCode = 1;
    }
    return;
  }

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, expected);
  console.log(`Updated ${path.relative(root, filePath)}`);
}

for (const target of compilationTargets) {
  const artifact = artifactFor(target.name, target.sourceName);
  const artifactPath = path.join(root, "artifacts", target.sourceName, `${target.name}.json`);
  assertOrWrite(artifactPath, `${JSON.stringify(artifact, null, 2)}\n`);
  if (target.publish) {
    const abiPath = path.join(root, "src", "Tricksfor.Blockchain.Booster", "Abis", `${target.name}Abi.cs`);
    assertOrWrite(abiPath, renderCSharp(target.name, artifact));
  }
}

const buildInfoDirectory = path.join(root, "artifacts", "build-info");
if (!checkOnly && fs.existsSync(buildInfoDirectory)) {
  for (const fileName of fs.readdirSync(buildInfoDirectory)) {
    if (fileName.startsWith("solc-0_8_26-") && !fileName.startsWith(buildInfoId)) {
      fs.unlinkSync(path.join(buildInfoDirectory, fileName));
    }
  }
}
assertOrWrite(
  path.join(buildInfoDirectory, `${buildInfoId}.json`),
  `${JSON.stringify({
    _format: "hh3-sol-build-info-1",
    id: buildInfoId,
    solcVersion: "0.8.26",
    solcLongVersion: solc.version(),
    compilerType: "solcjs",
    userSourceNameMap: Object.fromEntries(compilationTargets.map(({ sourceName }) => [sourceName, sourceName])),
    input
  }, null, 2)}\n`
);
assertOrWrite(
  path.join(buildInfoDirectory, `${buildInfoId}.output.json`),
  `${JSON.stringify({ _format: "hh3-sol-build-info-output-1", id: buildInfoId, output })}\n`
);

if (checkOnly && process.exitCode !== 1) {
  console.log(`Artifacts and Nethereum ABI/bytecode match solc ${solc.version()}.`);
}
